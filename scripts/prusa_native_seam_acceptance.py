"""Genuine 2.9.7 spatial seam regression, using generated MakerVault project."""
import hashlib
from pathlib import Path
import runpy
import subprocess
import sys
from tempfile import TemporaryDirectory

from slicer_worker.prusa_vendor_profiles import flatten_prusa_vendor_preset

auditor = runpy.run_path("/tmp/prusa_seam_audit.py")["audit_prusa_seam_enforcer_gcode"]
from scripts.prusa_generate_paint_fixtures import main as make_paint_fixtures


def run(binary, vendor):
    source = Path(vendor).read_bytes()
    digest = hashlib.sha256(source).hexdigest()
    with TemporaryDirectory(prefix="prusa-seam-acceptance-") as tmp:
        root = Path(tmp)
        make_paint_fixtures(str(root))
        options = []
        for kind, name in (("printer", "Original Prusa i3 MK2S"),
                           ("filament", "Generic PLA"),
                           ("print", "0.20mm NORMAL")):
            ini = root / (kind + ".ini")
            ini.write_bytes(flatten_prusa_vendor_preset(
                source, kind=kind, name=name, expected_sha256=digest))
            options += ["--load", str(ini)]
        fixture = runpy.run_path("/tmp/prusa_paint_fixture.py")
        # The exact input patch is generated by the same fixture as the 3MF.
        from scripts.prusa_real_binary_smoke import cube_stl
        from core.slicer_plate_3mf import _triangles
        from core.slicer_native_support_paint import _fingerprint
        raw = cube_stl()
        tris = list(_triangles(raw))
        bounds = [(min(p[i] for tri in tris for p in tri),
                   max(p[i] for tri in tris for p in tri)) for i in range(3)]
        centre = ((bounds[0][0]+bounds[0][1])/2,
                  (bounds[1][0]+bounds[1][1])/2, bounds[2][0])
        local = [[tuple(p[i]-centre[i] for i in range(3)) for p in tri] for tri in tris]
        face = next(i for i, tri in enumerate(local)
                    if max(p[2] for p in tri)-min(p[2] for p in tri) > 10
                    and (max(p[0] for p in tri)-min(p[0] for p in tri) < .0001
                         or max(p[1] for p in tri)-min(p[1] for p in tri) < .0001))
        patch = {"version":2,"signature":_fingerprint(local),
                 "regions":[{"slot":0,"patches":[{"face":face,"polygon":[list(p) for p in local[face]]}]}]}
        item = {"x_mm":0,"y_mm":0,"z_mm":0,"rotation_deg":0,"scale_percent":100,
                "seam_paint":patch}
        for name in ("baseline", "seam-enforced"):
            out = root / (name + ".gcode")
            subprocess.run([binary,*options,"--export-gcode","--dont-arrange",
                            "--output",str(out),str(root/(name+".3mf"))],
                           cwd=root,check=True,timeout=300)
        positive = auditor((root/"seam-enforced.gcode").read_bytes(), item,
                           bed_width=250,bed_depth=210)
        try:
            auditor((root/"baseline.gcode").read_bytes(), item,
                    bed_width=250,bed_depth=210)
        except ValueError:
            pass
        else:
            raise AssertionError("Baseline seam unexpectedly passed painted seam audit")
        print("PASS: native Prusa 2.9.7 seam enforcer spatially follows the specified triangle:", positive)


if __name__ == "__main__":
    run(*sys.argv[1:])
