"""Shared, comment-only thumbnail metadata for all native slicer engines."""
import base64
from io import BytesIO
import re

from django.test import SimpleTestCase
from PIL import Image

from core.slicer_gcode_thumbnails import add_gcode_thumbnails
from core.slicer_output import inspect_generated_gcode


SAMPLE = (
    b"; HEADER_BLOCK_START\n"
    b"; generated by Creality_Print V7.3.1.6378\n"
    b"; HEADER_BLOCK_END\n"
    b"; filament_colour = #7C7D7E;#FADD4D\n"
    b"; thumbnails = 96x96/PNG, 300x300/PNG\n"
    b"EXCLUDE_OBJECT_DEFINE NAME=cube1\n"
    b"EXCLUDE_OBJECT_START NAME=cube1\n"
    b"G90\nM83\nT0\nG1 X20 Y20 Z0.2 E0.5\n"
    b"G1 X30 Y20 E0.5\nG1 X30 Y30 E0.5\n"
    b"EXCLUDE_OBJECT_END NAME=cube1\n"
    b"EXCLUDE_OBJECT_START NAME=cube2\n"
    b"T1\nG1 X45 Y45 E0.5\nG1 X55 Y45 E0.5\n"
    b"G1 X55 Y55 E0.5\n"
    b"EXCLUDE_OBJECT_END NAME=cube2\n"
    b"; filament_type = PLA;PLA\n"
)


class SlicerGcodeThumbnailTests(SimpleTestCase):
    def _extract(self, raw):
        blocks = re.findall(
            rb"; thumbnail begin (\d+)x(\d+) (\d+)\n(.*?); thumbnail end\n",
            raw, flags=re.S,
        )
        found = []
        for width, height, declared, payload in blocks:
            data = b"".join(
                line.removeprefix(b"; ").strip()
                for line in payload.splitlines()
                if line.startswith(b"; ")
            )
            self.assertEqual(len(data), int(declared))
            with Image.open(BytesIO(base64.b64decode(data, validate=True))) as image:
                self.assertEqual(image.format, "PNG")
                self.assertEqual(image.size, (int(width), int(height)))
                found.append(image.size)
        return found

    def test_native_creality_header_kept_first_and_png_blocks_decode(self):
        enriched, sizes = add_gcode_thumbnails(SAMPLE)
        self.assertEqual(sizes, (96, 300))
        self.assertTrue(enriched.startswith(b"; HEADER_BLOCK_START\n"))
        self.assertIn(b"; HEADER_BLOCK_END\n\n; thumbnail begin", enriched)
        self.assertEqual(self._extract(enriched), [(96, 96), (300, 300)])
        self.assertIn(b"EXCLUDE_OBJECT_START NAME=cube1", enriched)
        self.assertIn(b"; filament_colour = #7C7D7E;#FADD4D", enriched)
        self.assertEqual(inspect_generated_gcode(enriched)["xy_moves"],
                         inspect_generated_gcode(SAMPLE)["xy_moves"])

    def test_fallback_png_is_transparent_and_antialiased(self):
        enriched, _ = add_gcode_thumbnails(SAMPLE)
        blocks = re.findall(
            rb"; thumbnail begin (\d+)x(\d+) (\d+)\n(.*?); thumbnail end\n",
            enriched, flags=re.S,
        )
        self.assertEqual(len(blocks), 2)
        for width, height, _, payload in blocks:
            data = b"".join(line.removeprefix(b"; ").strip()
                            for line in payload.splitlines() if line.startswith(b"; "))
            with Image.open(BytesIO(base64.b64decode(data))) as image:
                self.assertEqual(image.mode, "RGBA")
                self.assertEqual(image.getpixel((0, 0))[3], 0)
                alpha = image.getchannel("A")
                self.assertGreater(alpha.getextrema()[1], 0)
                # Downsampling creates genuinely smooth intermediate edges.
                self.assertTrue(any(0 < count < 255 for count in alpha.getdata()))
                self.assertEqual(image.size, (int(width), int(height)))

    def test_prusa_startup_purge_and_skirt_do_not_shrink_model(self):
        from core.slicer_gcode_thumbnails import _paths
        source = (
            "; generated by PrusaSlicer\n"
            ";TYPE:Custom\n"
            "G90\nM83\nG1 X10 Y-2 E5 ; intro line\n"
            "G1 X60 Y-2 E5 ; intro line\n"
            ";TYPE:Skirt/Brim\n"
            "G1 X80 Y80 E1\n"
            "G1 X85 Y80 E1\n"
            ";TYPE:External perimeter\n"
            "G0 X110 Y110\n"
            "G1 X120 Y110 E1\n"
            "G1 X120 Y120 E1\n"
        )
        segments, _ = _paths(source)
        self.assertEqual(len(segments), 2)
        self.assertTrue(all(min(segment[:4]) >= 110 for segment in segments))
        out, sizes = add_gcode_thumbnails(source.encode("utf-8"))
        self.assertEqual(sizes, (96, 300))
        self.assertEqual(self._extract(out), [(96, 96), (300, 300)])

    def test_orca_style_gcode_without_header_receives_same_blocks(self):
        source = (
            b"; generated by OrcaSlicer\n"
            b"; filament_colour = #aabbcc\n"
            b"G90\nM83\nT0\nG1 X1 Y1 E0.5\n"
            b"G1 X8 Y1 E0.5\nG1 X8 Y8 E0.5\n"
        )
        out, sizes = add_gcode_thumbnails(source)
        self.assertEqual(sizes, (96, 300))
        self.assertEqual(self._extract(out), [(96, 96), (300, 300)])
        self.assertTrue(out.endswith(source))

    def test_planned_engines_share_the_same_gcode_finaliser(self):
        # A thumbnail is based on deposited paths, not a vendor-specific
        # engine signature. The list covers current and roadmap integrations.
        engines = (
            "OrcaSlicer", "Creality Print", "BambuStudio", "PrusaSlicer",
            "Snapmaker Orca", "Ultimaker Cura", "ElegooSlicer",
            "Anycubic Slicer", "Flashforge",
        )
        for engine in engines:
            with self.subTest(engine=engine):
                source = (
                    ("; generated by " + engine + "\n").encode("utf-8")
                    + b"; filament_colour = #7C7D7E\n"
                    + b"G90\nM83\nT0\nG1 X1 Y1 E0.2\n"
                    + b"G1 X8 Y1 E0.2\nG1 X8 Y8 E0.2\n"
                )
                result, sizes = add_gcode_thumbnails(source)
                self.assertEqual(sizes, (96, 300))
                self.assertEqual(self._extract(result), [(96, 96), (300, 300)])
                self.assertTrue(result.endswith(source))

    def test_orca_native_png_qoi_jpg_and_cura_png_are_not_rewritten(self):
        for kind in (b"thumbnail", b"thumbnail_QOI", b"thumbnail_JPG",
                     b"thumbnail_PNG", b"png", b"jpg"):
            with self.subTest(format=kind):
                source = SAMPLE + b"; " + kind + b" begin 96x96 4\n; dGVz\n; " + kind + b" end\n"
                result, sizes = add_gcode_thumbnails(source)
                self.assertEqual((result, sizes), (source, ()))

    def test_bounded_sampler_retains_later_layers(self):
        from unittest.mock import patch
        from core.slicer_gcode_thumbnails import _paths
        commands = ["G90", "M83", "T0", "G1 X1 Y1 Z0.2 E1"]
        for layer in range(1, 34):
            commands.append(f"G1 X{layer + 1} Y1 Z{layer / 5:.2f} E1")
        with (patch("core.slicer_gcode_thumbnails.MAX_SEGMENTS", 6),
              patch("core.slicer_gcode_thumbnails.MAX_RENDER_SEGMENTS", 6)):
            segments, _ = _paths("\n".join(commands))
        self.assertGreater(len(segments), 0)
        self.assertTrue(any(segment[4] > 3.0 for segment in segments))

    def test_existing_native_thumbnail_is_preserved_exactly(self):
        native = SAMPLE + b"; thumbnail begin 96x96 4\n; dGVz\n; thumbnail end\n"
        out, sizes = add_gcode_thumbnails(native)
        self.assertEqual((out, sizes), (native, ()))
        out2, sizes2 = add_gcode_thumbnails(SAMPLE)
        out3, sizes3 = add_gcode_thumbnails(out2)
        self.assertEqual((out3, sizes3), (out2, ()))

    def test_missing_extrusion_or_binary_never_invents_thumbnail(self):
        for raw in (b"G0 X1 Y2\n", b"G90\nG1 X1 Y1\n",
                    b"\x00G1 X1 Y2 E1\n", b"\xffG1 X1 Y1 E1\n", b""):
            with self.subTest(raw=raw):
                self.assertEqual(add_gcode_thumbnails(raw), (raw, ()))

    def test_tool_selection_and_extrusion_commands_are_unchanged(self):
        out, _ = add_gcode_thumbnails(SAMPLE)
        def actual_commands(raw):
            return [line.strip() for line in raw.splitlines()
                    if line.strip() and not line.lstrip().startswith(b";")]
        self.assertEqual(actual_commands(out), actual_commands(SAMPLE))
