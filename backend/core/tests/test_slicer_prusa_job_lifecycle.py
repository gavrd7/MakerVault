"""Normal queued Prusa multi-tool job lifecycle with an audited-worker stub.

The pinned native CLI acceptance is separate. These tests prove that queued
jobs, output storage and unapproved-printer metadata use the production code,
without inventing a physical Prusa printer or external worker response.
"""
from unittest.mock import patch

from django.contrib.auth import get_user_model
from django.test import TestCase

from core.models import FileAsset, Printer, SliceJob
from core.slicer_execution import process_queued_job
from core.slicer_profiles import SlicerProfileError


class PrusaQueuedMaterialLifecycleTests(TestCase):
    def setUp(self):
        self.user = get_user_model().objects.create_user(
            username="prusa-queued-material-owner", password="not-used")
        self.printer = Printer.objects.create(
            owner=self.user, name="Offline profile test device", model="Test FDM")
        self.sources = [
            FileAsset.objects.create(
                owner=self.user, name=f"offline-part-{i}.stl", category="mesh",
                metadata={"extension":".stl",
                          "original_name":f"offline-part-{i}.stl"})
            for i in (0,1)
        ]
        self.objects = [
            {"asset_id":str(asset.pk), "instance_id":str(asset.pk),
             "x_mm":-35+70*i, "y_mm":0, "z_mm":0,
             "rotation_deg":0, "scale_percent":100}
            for i,asset in enumerate(self.sources)
        ]
        self.job = SliceJob.objects.create(
            owner=self.user, input_asset=self.sources[0],
            printer=self.printer, engine="prusaslicer",
            engine_version="2.9.7", printer_preset="Prusa native test",
            filament_preset="Generic PLA", process_preset="0.20mm NORMAL",
            nozzle_mm="0.4", status="queued",
            settings={"plate_objects":self.objects,
                      "multi_material_test":True,
                      "save_gcode_to_library":True},
        )

    def run_offline(self, *, failure=None):
        from contextlib import ExitStack
        with ExitStack() as patches:
            patches.enter_context(patch(
                "core.slicer_execution.verified_installation",
                return_value={"prusaslicer":{"version":"2.9.7"}}))
            admission=patches.enter_context(patch(
                "core.slicer_execution.validate_scheduling_for_worker"))
            load=patches.enter_context(patch(
                "core.slicer_execution._read_owned_file",
                return_value=b"verified private source STL"))
            worker=patches.enter_context(patch(
                "core.slicer_prusa_job_material.slice_prusa_workbench_material",
                side_effect=failure,
                return_value=(b"; generated by PrusaSlicer 2.9.7\n"
                              b"T0\nG1 X12 Y8 E0.5\n"
                              b"T1\nG1 X18 Y8 E0.6\n")))
            preview=patches.enter_context(patch(
                "core.tasks.warm_gcode_preview_task.delay"))
            unrelated=patches.enter_context(patch(
                "core.slicer_execution.run_remote_job"))
            result=process_queued_job(self.job.pk)
            admission.assert_called_once()
            self.assertEqual(load.call_count,3)
            worker.assert_called_once()
            unrelated.assert_not_called()
            self.job.refresh_from_db()
            if failure is None:
                preview.assert_called_once()
            else:
                preview.assert_not_called()
            return result

    def test_completed_offline_prusa_slice_is_a_private_library_gcode(self):
        result=self.run_offline()
        self.assertEqual(result["status"],"completed")
        self.assertEqual(self.job.status,"completed")
        asset=self.job.output_asset
        self.assertEqual(str(asset.pk),result["asset_id"])
        self.assertEqual(asset.category,"gcode")
        self.assertTrue(asset.metadata["multi_material_test"])
        self.assertTrue(asset.metadata["prusa_offline_native"])
        self.assertIs(asset.metadata["printer_submission_verified"],False)
        self.assertEqual(asset.metadata["source_review"]["status"],
                         "offline_native_only")
        self.assertEqual(asset.owner_id,self.user.pk)

    def test_failing_native_audit_never_stores_or_dispatches_a_print(self):
        result=self.run_offline(failure=SlicerProfileError(
            "Prusa native tool G-code did not match the assigned models."))
        self.assertEqual(result["status"],"failed")
        self.assertEqual(self.job.status,"failed")
        self.assertIsNone(self.job.output_asset_id)
        self.assertFalse(FileAsset.objects.filter(
            owner=self.user,category="gcode").exists())
        self.assertNotIn("assigned models",self.job.message)
