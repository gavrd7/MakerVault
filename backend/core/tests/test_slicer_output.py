from django.test import SimpleTestCase
from core.slicer_output import SlicerOutputError, inspect_generated_gcode


class SlicerOutputTests(SimpleTestCase):
    def test_accepts_bounded_plain_text_toolpath(self):
        report = inspect_generated_gcode(b"; generated by PrusaSlicer\nG1 X1 Y2 E0.3\n")
        self.assertGreater(report["xy_moves"], 0)
        self.assertFalse(report["partial"])

    def test_rejects_firmware_commands_and_binary_output(self):
        for body in (
            b"G1 X1 Y2\nM112\n", b"; comment\nN50 M500\nG1 X1 Y1\n",
            b"G1 X1 Y1\x00", b"", b"; metadata only\n",
        ):
            with self.subTest(body=body[:50]), self.assertRaises(SlicerOutputError):
                inspect_generated_gcode(body)
