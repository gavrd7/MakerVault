from django.test import SimpleTestCase
from core.slicer_output import SlicerOutputError, inspect_generated_gcode


class SlicerOutputTests(SimpleTestCase):
    def test_accepts_bounded_plain_text_toolpath(self):
        report = inspect_generated_gcode(b"; generated by PrusaSlicer\nG1 X1 Y2 E0.3\n")
        self.assertGreater(report["xy_moves"], 0)
        self.assertFalse(report["partial"])

    def test_rejects_firmware_commands_and_binary_output(self):
        for body in (
            b"G1 X1 Y2\nM112\n", b"; comment\nN50 M500\nG1 X1 Y1\n",
            b"G1 X1 Y1\x00", b"", b"; metadata only\n",
        ):
            with self.subTest(body=body[:50]), self.assertRaises(SlicerOutputError):
                inspect_generated_gcode(body)

from django.contrib.auth import get_user_model
from django.test import TestCase
from core.models import FileAsset, Printer, SliceJob
from core.slicer_output import store_generated_gcode, generated_slice_name


class GeneratedSlicerFileTests(TestCase):
    def setUp(self):
        user_model = get_user_model()
        self.owner = user_model.objects.create_user(username="slice-output", password="test")
        self.printer = Printer.objects.create(owner=self.owner, name="Printer", model="Generic")
        self.input_asset = FileAsset.objects.create(
            owner=self.owner, name="shape.stl", category="mesh",
            metadata={"extension": ".stl", "original_name": "shape.stl"},
        )
        self.job = SliceJob.objects.create(
            owner=self.owner, input_asset=self.input_asset, printer=self.printer,
            engine="prusaslicer", engine_version="2.9.7",
            printer_preset="Generic", filament_preset="PLA", process_preset="Normal",
            nozzle_mm="0.40", status="running",
        )

    def test_generated_filename_uses_source_stl_name(self):
        output = store_generated_gcode(self.job.pk, b"; generated\nG1 X1 Y1 E0.5\n")
        self.assertEqual(output.name, "shape.gcode")
        self.assertEqual(output.metadata["original_name"], "shape.gcode")
        self.assertNotIn(str(self.job.pk), output.name)

    def test_multi_object_plate_uses_both_source_names(self):
        second = FileAsset.objects.create(
            owner=self.owner, name="Lid.stl", category="mesh",
            metadata={"extension": ".stl", "original_name": "Lid.stl"},
        )
        self.job.settings = {"plate_objects": [
            {"asset_id": str(self.input_asset.pk)},
            {"asset_id": str(second.pk)},
        ]}
        self.job.save(update_fields=["settings"])
        self.assertEqual(generated_slice_name(self.job), "shape + Lid.gcode")

    def test_source_filenames_are_sanitized_and_bounded(self):
        self.input_asset.name = "example.stl"
        self.input_asset.metadata = {
            "extension": ".stl",
            "original_name": "../" + "A" * 300 + ":model?.stl",
        }
        self.input_asset.save(update_fields=["name", "metadata"])
        filename = generated_slice_name(self.job)
        self.assertLessEqual(len(filename), 62)
        self.assertTrue(filename.endswith(".gcode"))
        self.assertNotIn("/", filename)
        self.assertNotIn("?", filename)
        self.assertNotIn(":", filename)

    def test_generated_output_is_private_until_explicitly_saved(self):
        from core.models import PrinterGcodeSubmission
        before = PrinterGcodeSubmission.objects.count()
        output = store_generated_gcode(self.job.pk, b"; generated\nG1 X1 Y1 E0.5\n")
        self.job.refresh_from_db()
        self.assertEqual(self.job.status, "completed")
        self.assertEqual(self.job.output_asset_id, output.pk)
        self.assertEqual(output.category, "other")
        self.assertEqual(output.metadata["slicer_library_status"], "pending")
        self.assertEqual(output.owner_id, self.owner.pk)
        self.assertEqual(output.metadata["generated_by"], "makervault-slicer")
        self.assertEqual(PrinterGcodeSubmission.objects.count(), before)
        with self.assertRaises(SlicerOutputError):
            store_generated_gcode(self.job.pk, b"G1 X2 Y2\n")

    def test_opt_in_auto_adds_completed_output_to_gcode_library(self):
        self.job.settings = {"save_gcode_to_library": True}
        self.job.save(update_fields=["settings"])
        output = store_generated_gcode(self.job.pk, b"; generated\nG1 X1 Y1 E0.5\n")
        self.assertEqual(output.category, "gcode")
        self.assertEqual(output.metadata["slicer_library_status"], "saved")

    def test_owner_must_explicitly_promote_private_completed_output(self):
        from django.contrib.auth.models import Permission
        output = store_generated_gcode(self.job.pk, b"; generated\nG1 X1 Y1 E0.5\n")
        endpoint = f"/api/printing/slicer/jobs/{self.job.pk}/save-gcode/"
        other = get_user_model().objects.create_user(username="unrelated-slice-user", password="test")
        self.client.force_login(other)
        self.assertEqual(self.client.post(endpoint).status_code, 403)
        self.owner.user_permissions.add(Permission.objects.get(codename="add_fileasset"))
        self.client.force_login(self.owner)
        response = self.client.post(endpoint, data="{}", content_type="application/json")
        self.assertEqual(response.status_code, 200, response.content)
        output.refresh_from_db()
        self.assertEqual(output.category, "gcode")
        self.assertEqual(output.metadata["slicer_library_status"], "saved")
        self.assertEqual(self.client.post(endpoint, data="{}", content_type="application/json").status_code, 200)
        self.assertEqual(FileAsset.objects.filter(owner=self.owner, category="gcode").count(), 1)

    def test_cannot_promote_an_unsliced_draft(self):
        self.job.status = "draft"
        self.job.save(update_fields=["status"])
        self.owner.user_permissions.add(
            __import__("django.contrib.auth.models", fromlist=["Permission"]).Permission.objects.get(codename="add_fileasset")
        )
        self.client.force_login(self.owner)
        endpoint = f"/api/printing/slicer/jobs/{self.job.pk}/save-gcode/"
        self.assertEqual(self.client.post(endpoint, data="{}", content_type="application/json").status_code, 404)
