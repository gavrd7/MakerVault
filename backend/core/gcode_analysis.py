"""Bounded, read-only analysis of user-uploaded plain-text G-code.

Metadata is evidence, not proof of printer compatibility. Never execute commands.
Binary BGCODE and unknown dialects must not be treated as safe to print.
"""
import math
import re

MAX_PREVIEW_BYTES = 256 * 1024
MAX_SCAN_BYTES = 32 * 1024 * 1024
MAX_LINE = 4096
NUMBER = re.compile(r"^[-+]?(?:\d+(?:\.\d*)?|\.\d+)$")
AXIS = re.compile(r"([XYZEF])\s*([-+]?(?:\d+(?:\.\d*)?|\.\d+))", re.I)
HEADER_PRINTER = re.compile(
    r"^;\s*(?:printer_model|printer model|printer_name|printer name|machine_name|machine name|machine|printer)\s*[:=]\s*(.+?)\s*$",
    re.I,
)
HEADER_SLICER = re.compile(r"^;\s*(?:generated by|sliced by|slicer)\s*[:=]?\s*(.+?)\s*$", re.I)
DANGEROUS = {"M112", "M500", "M501", "M502", "M997"}

FILAMENT_HEADER = re.compile(
    r"^;\s*(filament_type|filament_colour|filament_color|filament_settings_id|material[ _]type|material[ _]color|material[ _]colour)\s*[:=]\s*(.*?)\s*$",
    re.I,
)
PRINT_SETUP_HEADER = re.compile(
    r"^;\s*(nozzle_diameter|nozzle diameter|nozzle_size|nozzle size|curr_bed_type|bed_type|bed type|plate_type|plate type|build_plate_type|build plate type)\s*[:=]\s*(.*?)\s*$",
    re.I,
)
NOZZLE_KEYS = {"nozzle_diameter", "nozzle diameter", "nozzle_size", "nozzle size"}
BED_KEYS = {"curr_bed_type", "bed_type", "bed type", "plate_type", "plate type", "build_plate_type", "build plate type"}


def _print_setup(text):
    """Extract only explicit slicer-declared nozzle and build-plate metadata."""
    nozzle = []
    bed_type = None
    sources = {}
    for line in text.splitlines():
        if len(line) > MAX_LINE:
            continue
        match = PRINT_SETUP_HEADER.match(line.strip())
        if not match:
            continue
        key = match.group(1).lower()
        value = match.group(2).strip().strip('"').strip("'")[:120]
        if key in NOZZLE_KEYS and not nozzle:
            # Slicers may declare multiple extruder nozzle diameters.
            entries = re.split(r"[,;]", value)
            parsed = []
            for entry in entries:
                candidate = entry.strip().lower().removesuffix("mm").strip()
                if not NUMBER.fullmatch(candidate):
                    parsed = []
                    break
                diameter = float(candidate)
                if not math.isfinite(diameter) or not 0.1 <= diameter <= 2.0:
                    parsed = []
                    break
                parsed.append(round(diameter, 3))
            if parsed and len(parsed) <= 16:
                nozzle = parsed
                sources["nozzle"] = key
        elif key in BED_KEYS and bed_type is None and value:
            # A label is not evidence of the plate physically fitted.
            bed_type = value
            sources["bed_type"] = key
    return {"nozzle_diameters_mm": nozzle, "bed_type": bed_type, "sources": sources}


HEX_COLOUR = re.compile(r"^#[0-9A-Fa-f]{6}$")
MATERIAL_TYPES = ("PLA", "PETG", "ABS", "ASA", "TPU", "PC", "PA", "PVA", "HIPS", "PCTG")


FILAMENT_USAGE_HEADER = re.compile(
    r"^;\s*filament\s*used\s*\[(mm|g|cm3)\]\s*[:=]\s*(.*?)\s*$", re.I
)


def _declared_used_filaments(text, count):
    """Use slicer per-profile measured consumption only with a complete vector."""
    if not 1 <= count <= 16:
        return None
    found = {}
    for raw in text.splitlines():
        if len(raw) > MAX_LINE:
            continue
        match = FILAMENT_USAGE_HEADER.match(raw.strip())
        if match:
            found.setdefault(match.group(1).lower(), match.group(2))
    for unit in ("mm", "g", "cm3"):
        value = found.get(unit)
        if value is None:
            continue
        entries = [item.strip() for item in re.split(r"[,;]", value)]
        if len(entries) != count or not all(NUMBER.fullmatch(item) for item in entries):
            continue
        values = [float(item) for item in entries]
        if not all(math.isfinite(item) and item >= 0 for item in values):
            continue
        used = [index for index, amount in enumerate(values) if amount > 0.000001]
        if used:
            return {"used_tool_indices": used, "usage_confident": True, "usage_source": "slicer_consumption_" + unit,
                    "usage_reason": ""}
    return None


TOOL_SELECT = re.compile(r"^T(\d{1,2})(?:\s|$)", re.I)
E_VALUE = re.compile(r"(?:^|\s)E\s*([-+]?(?:\d+(?:\.\d*)?|\.\d+))(?=\s|$)", re.I)


def _used_extrusion_tools(text, *, declared_count, truncated=False):
    """Conservatively identify tools depositing material, not merely configured.

    Only planar G0/G1 moves with a positive E delta count as deposition.
    T0/T1... select slicer tool indices. G92 E, M82/M83 and G90/G91 are
    tracked separately; ambiguous dialects and bounded scans fail to unknown.
    """
    active = None
    seen_tool = False
    extruding = set()
    e_absolute = True
    e_position = 0.0
    ambiguous = False
    detected_deposition = False
    unassigned_depositions = 0
    seen_tools = set()
    for raw in text.splitlines():
        if len(raw) > MAX_LINE:
            ambiguous = True
            continue
        line = raw.split(";", 1)[0].strip().upper()
        if not line:
            continue
        match = TOOL_SELECT.match(line)
        if match:
            active = int(match.group(1))
            seen_tool = True
            seen_tools.add(active)
            if active >= max(1, declared_count):
                ambiguous = True
            continue
        code = line.split(None, 1)[0]
        compact = re.match(r"^(G0?[01]|G92)(?=\s|[XYZE])", line)
        if compact:
            code = compact.group(1)
        if code in {"M82", "M83"}:
            e_absolute = code == "M82"
        elif code == "G92":
            e = E_VALUE.search(line[len(code):]) or re.search(r"E\s*([-+]?(?:\d+(?:\.\d*)?|\.\d+))", line[len(code):])
            if e:
                e_position = float(e.group(1))
        elif code in {"G0", "G00", "G1", "G01"}:
            args = line[len(code):]
            e = E_VALUE.search(args) or re.search(r"E\s*([-+]?(?:\d+(?:\.\d*)?|\.\d+))", args)
            if not e:
                continue
            amount = float(e.group(1))
            delta = amount - e_position if e_absolute else amount
            if e_absolute:
                e_position = amount
            if delta <= 0.000001 or not re.search(r"[XY]\s*[-+]?\d", args):
                continue
            detected_deposition = True
            if active is None:
                # Only an explicitly single-profile file has an unambiguous
                # default tool. Do not assume T0 for four declared profiles.
                if declared_count == 1 and not seen_tool:
                    extruding.add(0)
                else:
                    ambiguous = True
                    unassigned_depositions += 1
            else:
                extruding.add(active)
        elif code in {"G10", "G11", "M163", "M164", "M567"}:
            # These commands can change feedstock without a normal T command.
            ambiguous = True
    known = bool(extruding) and detected_deposition and not ambiguous and not truncated
    return {"used_tool_indices": sorted(extruding) if known else [],
            "toolpath_evidence": {"selected_tools": sorted(seen_tools),
                                  "extruding_tools": sorted(extruding),
                                  "unassigned_extrusions": unassigned_depositions},
            "usage_source": "toolpath_extrusion" if known else "unknown",
            "usage_confident": known,
            "usage_reason": ("" if known else
                "Actual depositing tools could not be determined from this G-code; the slicer's original mapping can still be used.")}


def _filament_requirements(text, *, truncated):
    """Extract advisory slicer filament declarations; never infer a printer mapping.

    Only explicitly declared slicer header vectors are trusted as requirements.
    A tool change in G-code alone does not prove material or slot assignment.
    """
    found = {}
    for line in text.splitlines():
        if len(line) > MAX_LINE or not line.lstrip().startswith(";"):
            continue
        match = FILAMENT_HEADER.match(line.strip())
        if match and match.group(1).lower() not in found:
            found[match.group(1).lower()] = match.group(2)[:1024]
    def split_vector(value):
        return [part.strip().strip('"')[:120] for part in (value.split(";") if ";" in value else value.split(","))] if value else []
    types = split_vector(found.get("filament_type") or found.get("material type") or found.get("material_type") or "")
    colours = split_vector(found.get("filament_colour") or found.get("filament_color") or found.get("material color") or found.get("material colour") or "")
    presets = split_vector(found.get("filament_settings_id", ""))
    count = max(len(types), len(colours), len(presets))
    if count > 16:
        return {"requirements": [], "complete": False, "reason": "Slicer declares too many filaments to review safely."}
    requirements = []
    for index in range(count):
        material = types[index].upper() if index < len(types) else ""
        colour = colours[index] if index < len(colours) else ""
        preset = presets[index] if index < len(presets) else ""
        if not HEX_COLOUR.fullmatch(colour):
            colour = ""
        # Preserve unknown material rather than incorrectly treating product names as chemistry.
        if material and not any(material == kind or (material.startswith(kind + "-") or material.startswith(kind + "+")) for kind in MATERIAL_TYPES):
            material = ""
        requirements.append({
            "tool_index": index, "material": material, "color_hex": colour.lower(),
            "preset": preset, "complete": bool(material and colour),
        })
    tool_usage = _used_extrusion_tools(text, declared_count=count, truncated=truncated)
    declared_usage = None if truncated else _declared_used_filaments(text, count)
    if declared_usage is not None:
        # The slicer's final accounting is a better source than tooling during
        # prime/purge macros. If both analyses are definite but disagree, fail
        # closed instead of silently mapping a different tool.
        if tool_usage["usage_confident"] and tool_usage["used_tool_indices"] != declared_usage["used_tool_indices"]:
            tool_usage = {"used_tool_indices": [], "usage_confident": False,
                          "usage_source": "conflicting_evidence",
                          "usage_reason": "Toolpath and slicer filament consumption disagree."}
        else:
            tool_usage = {**declared_usage, "toolpath_evidence": tool_usage.get("toolpath_evidence", {})}
    used = [item for item in requirements if item["tool_index"] in tool_usage["used_tool_indices"]]
    complete = bool(requirements) and all(item["complete"] for item in requirements) and not truncated
    used_complete = bool(used) and all(item["complete"] for item in used) and not truncated
    return {
        "requirements": requirements, "complete": complete,
        "used_requirements": used,
        "used_complete": used_complete,
        **tool_usage,
        "reason": ("" if complete else "Sliced filament type/colour metadata is incomplete or not available; manual review is required."),
    }




def analyse_text(text, *, truncated=False):
    """Parse only selected safe metadata; preview toolpaths are advisory."""
    printer_hints = []
    slicer_hints = []
    warnings = []
    moves = 0
    preview_points = []
    bounds = {axis: [None, None] for axis in "XYZ"}
    position = {"X": 0.0, "Y": 0.0, "Z": 0.0}
    absolute = True
    units_mm = True
    risky = set()
    filaments = _filament_requirements(text, truncated=truncated)
    print_setup = _print_setup(text)
    for raw in text.splitlines():
        if len(raw) > MAX_LINE:
            continue
        line = raw.strip()
        if line.startswith(";"):
            if len(printer_hints) < 8:
                found = HEADER_PRINTER.match(line)
                if found:
                    value = found.group(1).strip().strip('"')[:120]
                    if value and value not in printer_hints:
                        printer_hints.append(value)
            if len(slicer_hints) < 4:
                found = HEADER_SLICER.match(line)
                if found:
                    value = found.group(1).strip()[:120]
                    if value and value not in slicer_hints:
                        slicer_hints.append(value)
            continue
        command = line.split(";", 1)[0].split("(", 1)[0].strip().upper()
        if not command:
            continue
        code = command.split(None, 1)[0]
        if code in DANGEROUS:
            risky.add(code)
        if code == "G90":
            absolute = True
        elif code == "G91":
            absolute = False
        elif code == "G20":
            units_mm = False
        elif code == "G21":
            units_mm = True
        elif code in {"G0", "G00", "G1", "G01"}:
            moves += 1
            for axis, raw_value in AXIS.findall(command[len(code):]):
                axis = axis.upper()
                if axis not in position or not NUMBER.fullmatch(raw_value):
                    continue
                value = float(raw_value)
                if not math.isfinite(value):
                    continue
                value *= 1.0 if units_mm else 25.4
                position[axis] = value if absolute else position[axis] + value
                if not math.isfinite(position[axis]):
                    continue
                low, high = bounds[axis]
                bounds[axis] = [position[axis] if low is None else min(low, position[axis]),
                                position[axis] if high is None else max(high, position[axis])]
            if len(preview_points) < 3000:
                preview_points.append([round(position['X'], 3), round(position['Y'], 3), round(position['Z'], 3)])
    if truncated:
        warnings.append("File was only partially analysed; bounds and metadata may be incomplete.")
    if not printer_hints:
        warnings.append("No explicit intended printer metadata found. Printer compatibility is unknown.")
    if not units_mm:
        warnings.append("Inch-unit commands were detected; validate printer and toolpath carefully.")
    if risky:
        warnings.append("Contains firmware/control commands requiring manual review: " + ", ".join(sorted(risky)))
    return {
        "filaments": filaments,
        "print_setup": print_setup,
        "printer_hints": printer_hints,
        "slicer_hints": slicer_hints,
        "xy_moves": moves,
        "bounds_mm": bounds,
        "xy_preview": preview_points,
        "xy_preview_sampled": moves > len(preview_points),
        "partial": truncated,
        "warnings": warnings,
        "compatibility": "unverified",
    }




def compare_printer_metadata(report, printer):
    """Compare explicit slicer model hints with a selected owned printer.

    This is a conservative preflight signal, not proof that G-code is safe.
    No adapter is called. An actual print-start must recheck compatibility.
    """
    hints = report.get("printer_hints") or []
    catalog = printer.catalog_model
    manufacturer = printer.printer_manufacturer

    def normalise(value):
        value = re.sub(r"[^A-Z0-9]+", " ", str(value or "").upper()).strip()
        vendor = (getattr(manufacturer, "name", "") or "").upper()
        if vendor and value.startswith(vendor + " "):
            value = value[len(vendor):].strip()
        if value.startswith("CREALITY "):
            value = value[len("CREALITY "):]
        return " ".join(value.split())

    names = [printer.model, getattr(catalog, "name", ""), printer.name]
    expected = {normalise(name) for name in names if name}
    supplied = {normalise(hint) for hint in hints if hint}
    supplied.discard("")
    expected.discard("")
    if not supplied:
        return {"status": "unknown", "reason": "G-code does not name an intended printer.", "blocking": True}
    if supplied & expected:
        return {"status": "metadata_match", "reason": "The explicit printer name agrees with the selected model; this is not a safety guarantee.", "blocking": False}

    def creality_series(value):
        found = re.search(r"\b(K1C|K1|K2)\b", value)
        return found.group(1) if found else None

    source_series = {creality_series(value) for value in supplied}
    target_series = {creality_series(value) for value in expected}
    source_series.discard(None)
    target_series.discard(None)
    # Distinguish K1 and K2 without substring matches; never call unknown "safe".
    if source_series and target_series and source_series.isdisjoint(target_series):
        return {
            "status": "mismatch",
            "reason": "G-code targets " + ", ".join(sorted(source_series)) +
                      " but the selected printer is " + ", ".join(sorted(target_series)) +
                      ". Do not start this file on the selected printer.",
            "blocking": True,
        }
    return {
        "status": "unknown",
        "reason": "The slicer printer profile could not be matched confidently to the selected model.",
        "blocking": True,
    }

def inspect_asset(asset):
    """Read a bounded prefix from private storage, never perform printer I/O."""
    filename = str((asset.metadata or {}).get("original_name") or asset.name or "")
    if not filename.lower().endswith(".gcode"):
        raise ValueError("Only plain-text .gcode files can be inspected.")
    with asset.file.storage.open(asset.file.name, "rb") as handle:
        sample = handle.read(MAX_SCAN_BYTES + 1)
    truncated = len(sample) > MAX_SCAN_BYTES
    sample = sample[:MAX_SCAN_BYTES]
    if b"\x00" in sample[:MAX_PREVIEW_BYTES]:
        raise ValueError("Binary G-code cannot be shown as editable text.")
    text = sample.decode("utf-8", errors="replace")
    report = analyse_text(text, truncated=truncated)
    if (asset.metadata or {}).get("generated_by") == "makervault-slicer":
        from .slicer_preview import generated_preview
        report["slicer_preview"] = generated_preview(text, truncated=truncated)
    preview = sample[:MAX_PREVIEW_BYTES].decode("utf-8", errors="replace")
    if len(sample) > MAX_PREVIEW_BYTES:
        preview = preview.rsplit("\n", 1)[0]
    return {"analysis": report, "preview": preview, "preview_truncated": len(sample) > MAX_PREVIEW_BYTES or truncated}
