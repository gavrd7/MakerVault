def _geometry_control_project(project, feature):
    """Keep *identical* remeshed triangles, colours and native presets.

    Remove only the semantic paint attribute being measured. A native slice
    of this control is the appropriate comparator, not the original mesh
    whose triangulation changes when a brush patch is applied.
    """
    attribute = _SEMANTIC_ATTRS[feature]
    result = io.BytesIO()
    removed = 0
    with zipfile.ZipFile(io.BytesIO(project)) as source, zipfile.ZipFile(
            result, "w", compression=zipfile.ZIP_DEFLATED,
            allowZip64=False) as output:
        for info in source.infolist():
            body = source.read(info.filename)
            if info.filename == "3D/3dmodel.model":
                root = ET.fromstring(body)
                for triangle in root.iter(_CORE_NS + "triangle"):
                    if attribute in triangle.attrib:
                        triangle.attrib.pop(attribute)
                        removed += 1
                body = ET.tostring(root, encoding="utf-8", xml_declaration=True)
            output.writestr(info.filename, body)
    if not removed:
        raise ValueError("Diagnostic patch produced no native painted facets.")
    return result.getvalue(), removed


def _support_auto_control_project(unpainted_project):
    """Keep the identical unpainted cantilever, changing only manual to auto.

    This comparison isolates whether ordinary automatic support can be
    generated by the native engine at all using the selected K2 profile.
    No saved profiles, engine binaries or source files are modified.
    """
    source_bytes = bytes(unpainted_project)
    if len(source_bytes) > 32 * 1024 * 1024:
        raise ValueError("Support control 3MF exceeds diagnostic size limit.")
    output = io.BytesIO()
    replaced = False
    with zipfile.ZipFile(io.BytesIO(source_bytes), "r") as source, zipfile.ZipFile(
            output, "w", compression=zipfile.ZIP_DEFLATED,
            allowZip64=False) as dest:
        names = source.namelist()
        if len(names) != len(set(names)) or len(names) > 16:
            raise ValueError("Invalid support-control archive member list.")
        for info in source.infolist():
            value = source.read(info.filename)
            if info.filename == "Metadata/project_settings.config":
                config = json.loads(value)
                if (str(config.get("enable_support")) != "1" or
                        config.get("support_type") != "normal(manual)"):
                    raise ValueError("Support control requires manually enabled native supports.")
                config["support_type"] = "normal(auto)"
                _mark_creality_support_overrides(config, ("enable_support", "support_type"))
                value = json.dumps(config, separators=(",", ":")).encode("utf-8")
                replaced = True
            dest.writestr(info.filename, value)
    if not replaced:
        raise ValueError("Support control has no native process settings.")
    return output.getvalue()


